#!/usr/bin/env node
/**
 * Renders every message the app can send into `docs/mail/`.
 *
 * A mail template is a function whose output nobody reads: the wording lives in
 * a config file, the layout in another module, and what a customer actually
 * receives exists only in an inbox. So the previews are committed — both parts
 * of every message, exactly as the mailer would send them — and a reworded
 * template shows up as a reviewable diff.
 *
 * The gallery doubles as the reference for what the order-journey specs assert
 * about mail: the subjects they match on are the subjects listed here.
 *
 * Run `node tools/generate-mail-previews.mjs` after changing a template, the
 * layout, or the demo wording. `--check` verifies the committed files match,
 * which is what CI runs.
 */
import { readdirSync } from 'node:fs';
import { loadTypeScript, writeOrCheck } from './lib/generated-docs.mjs';

const DIR = 'docs/mail';
const COMMAND = 'tools/generate-mail-previews.mjs';

const { renderMailPreviews, demoMailBranding } = await loadTypeScript(
  'apps/api/src/mail/mail-previews.ts',
);
const previews = renderMailPreviews();

const files = {};
for (const preview of previews) {
  files[`${DIR}/${preview.slug}.html`] = preview.rendered.html;
  files[`${DIR}/${preview.slug}.txt`] = preview.rendered.text;
}
files[`${DIR}/README.md`] = renderIndex(previews);

/**
 * The index is what a person reads first: what each message is for, when it is
 * sent, and the subject line it arrives under — the one field a reader
 * recognises a mail by, and the one the journey specs assert on.
 */
function renderIndex(previews) {
  const rows = previews.map(
    (preview) =>
      `### ${preview.title}\n\n` +
      `${preview.note}\n\n` +
      `**Subject:** ${preview.rendered.subject}  \n` +
      `**Preheader:** ${preview.content.preheader}\n\n` +
      `[HTML](${preview.slug}.html) · [Plain text](${preview.slug}.txt)\n`,
  );
  return [
    '<!-- Generated by tools/generate-mail-previews.mjs — do not edit by hand. -->',
    '',
    '# Email gallery',
    '',
    'Every message the app can send, rendered from the demo wording in',
    '`mail-text.fixture.ts`. Both parts of each message are committed as the',
    'mailer would send them: open the `.html` in a browser to see it, read the',
    '`.txt` to review a change without wading through table markup.',
    '',
    'Nothing here is deployment content. The wording each deployment ships is',
    'its own mounted `mail-text.json`, and the branding below is illustrative:',
    `**${demoMailBranding.name}**, ${demoMailBranding.primaryColor}, ${demoMailBranding.siteUrl}.`,
    '',
    ...rows,
  ].join('\n');
}

/** A preview that was renamed or removed must not leave its old file behind. */
let existing = [];
try {
  existing = readdirSync(DIR);
} catch {
  existing = [];
}
const orphans = existing
  .map((name) => `${DIR}/${name}`)
  .filter((path) => !(path in files));
if (orphans.length > 0) {
  console.error(
    `${DIR} holds files no preview produces — delete them:\n${orphans
      .map((path) => `  ${path}`)
      .join('\n')}`,
  );
  process.exit(1);
}

writeOrCheck(files, COMMAND);
