#!/usr/bin/env node
/**
 * Emits the browser's copy of the API contracts: routes only, no schemas. The
 * oRPC link reads only `method`, `path`, `inputStructure` and
 * `outputStructure`; the real contract would ship every schema and Zod, ~118
 * kB that never runs. `minifyContractRouter` makes plain data, which the
 * structural `isContractProcedure` accepts.
 *
 * Run `node tools/generate-contract-routes.mjs` after changing a route's
 * method, path or input/output structure; schema edits change nothing here.
 * `--check` verifies the committed files match, which is what CI runs.
 */
import { build } from 'esbuild';
import { minifyContractRouter } from '@orpc/contract';
import { execFileSync } from 'node:child_process';
import { existsSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { pathToFileURL } from 'node:url';

/**
 * The contracts the web app calls, per entry point. Each entry's routes are
 * written into the web folder of the same name, so an area imports only its
 * own and `platform/` names no area.
 */
const ENTRIES = {
  platform: ['sessionContract'],
  'core/accounts': [
    'addressSuggestionContract',
    'addressesContract',
    'partySuggestionContract',
  ],
  'core/site': ['maintenanceContract', 'pageContract'],
  'core/work': ['workContract'],
  'storefront/accounts': ['accountContract', 'authContract'],
  'storefront/catalog': ['catalogContract'],
  'storefront/ordering': ['cartContract', 'ordersContract'],
  'storefront/site': ['inquiryContract'],
  'admin/accounts': ['consentsContract', 'usersContract'],
  'admin/catalog': [
    'adminCategoriesContract',
    'adminProductsContract',
    'attributesContract',
    'documentsContract',
    'tiersContract',
  ],
  'admin/exchange': [
    'adminOwnershipSwitchContract',
    'adminApiTokensContract',
    'adminSyncContract',
  ],
  'admin/ordering': ['adminOrdersContract'],
  'admin/platform': ['adminOperationsContract', 'adminOwnershipContract'],
  'admin/site': ['adminMaintenanceContract', 'adminPagesContract'],
};

const OUTPUTS = Object.entries(ENTRIES).map(([entry, names]) => ({
  file: `apps/web/src/app/${entry}/contract-routes.generated.ts`,
  entries: { [entry]: names },
}));

/** The fields the client link actually reads; everything else is server-side. */
const CLIENT_ROUTE_FIELDS = [
  'method',
  'path',
  'inputStructure',
  'outputStructure',
];

/** Loads one entry point's contracts by bundling it into a module Node can run. */
async function loadContracts(entry) {
  // Inside the workspace, not the system temp dir: the bundle leaves its
  // dependencies external, so it has to sit where node_modules resolves.
  const outfile = `node_modules/.contract-routes-${entry.replace('/', '-') || 'root'}.mjs`;
  try {
    await build({
      entryPoints: [`libs/shared/src/${entry ? `${entry}/` : ''}index.ts`],
      outfile,
      bundle: true,
      format: 'esm',
      platform: 'node',
      packages: 'external',
      logLevel: 'silent',
    });
    return await import(pathToFileURL(outfile).href);
  } finally {
    rmSync(outfile, { force: true });
  }
}

/** Drops the OpenAPI documentation fields a browser has no use for. */
function stripToClientFields(node) {
  if (node && typeof node === 'object' && '~orpc' in node) {
    const route = {};
    for (const field of CLIENT_ROUTE_FIELDS) {
      const value = node['~orpc'].route?.[field];
      if (value !== undefined) route[field] = value;
    }
    return { '~orpc': { errorMap: {}, meta: {}, route } };
  }
  const result = {};
  for (const key of Object.keys(node)) {
    result[key] = stripToClientFields(node[key]);
  }
  return result;
}

async function render({ entries }) {
  const imports = [];
  const exports = [];
  for (const [entry, names] of Object.entries(entries)) {
    // `admin/catalog` is imported as `adminCatalog`.
    const alias =
      entry.replace(/\/(\w)/g, (_, letter) => letter.toUpperCase()) || 'shared';
    const contracts = await loadContracts(entry);
    imports.push(
      `import type * as ${alias} from '@b2b-catalog-platform/shared${entry ? `/${entry}` : ''}';`,
    );
    for (const name of names) {
      const routes = stripToClientFields(minifyContractRouter(contracts[name]));
      exports.push(
        `export const ${name} = ${JSON.stringify(routes)} as unknown as typeof ${alias}.${name};`,
      );
    }
  }
  return [
    '// Generated by tools/generate-contract-routes.mjs — do not edit by hand.',
    '//',
    '// The routes the oRPC client needs, without the schemas it never runs.',
    '// Typed as the real contract, so every call site keeps the types the',
    '// contract defines; the imports below are type-only and erased at build.',
    '',
    ...imports,
    '',
    ...exports,
    '',
  ].join('\n');
}

let stale = false;
for (const output of OUTPUTS) {
  const generated = execFileSync(
    'npx',
    ['prettier', '--parser', 'typescript'],
    {
      input: await render(output),
      encoding: 'utf8',
    },
  );
  if (process.argv.includes('--check')) {
    const current = existsSync(output.file)
      ? readFileSync(output.file, 'utf8')
      : '';
    if (current !== generated) {
      console.error(
        `${output.file} is out of date — run \`node tools/generate-contract-routes.mjs\`.`,
      );
      stale = true;
    }
  } else {
    writeFileSync(output.file, generated);
    console.log(`contract routes: wrote ${output.file}.`);
  }
}
if (stale) process.exit(1);
if (process.argv.includes('--check'))
  console.log('contract routes: up to date.');
